// Builds src/tokens.css from design-system/tokens.json, so no colour is hard-coded in the app.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(resolve(here, "../../design-system/tokens.json"), "utf8"));

const light = [];
const dark = [];
for (const t of tokens.color.tokens) {
  if (typeof t.value === "string") {
    light.push(`--${t.name}: ${t.value};`);
  } else {
    light.push(`--${t.name}: ${t.value.light};`);
    dark.push(`--${t.name}: ${t.value.dark};`);
  }
}
// design-system/README.md: "Large brand fields use brand-fill with white text."
light.push("--on-brand-fill: #FFFFFF;");
for (const t of tokens.shadow.tokens) {
  light.push(`--${t.name}: ${t.value.light};`);
  dark.push(`--${t.name}: ${t.value.dark};`);
}
for (const t of [...tokens.spacing.tokens, ...tokens.radius.tokens]) {
  light.push(`--${t.name}: ${t.value};`);
}
for (const [name, value] of Object.entries(tokens.type.families)) {
  light.push(`--font-${name}: ${value};`);
}
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    light.push(`--type-${s.name}-size: ${s.fontSize};`);
    light.push(`--type-${s.name}-line: ${s.lineHeight};`);
    light.push(`--type-${s.name}-weight: ${s.fontWeight};`);
  }
}

const indent = (lines) => lines.map((l) => `  ${l}`).join("\n");
const css = `/* Generated by scripts/tokens.mjs from design-system/tokens.json. Do not edit. */
:root {
${indent(light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent(dark).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${indent(dark)}
  color-scheme: dark;
}
`;
writeFileSync(resolve(here, "../src/tokens.css"), css);
